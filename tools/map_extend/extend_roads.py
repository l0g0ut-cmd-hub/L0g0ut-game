out = {}
for r, m in OLD.items():
    w = W[r]; u = 1536.0 / w
    sc = lambda x, y: [round(x * u, 4), round(y, 4)]
    ren = lambda n: "E" if n == "Z" else n
    spots = [[[ren(n), *sc(x, y)] for n, x, y in layer] for layer in m["spots"]]
    lair = spots[-1][0][1:]
    nw = NEW[r]
    # бывшее логово — в один слой с первым новым местом
    spots[-1] = spots[-1] + [[n, round(x / w, 4), round(y / 1024, 4)] for n, x, y in nw["layers"][0]]
    for layer in nw["layers"][1:]:
        spots.append([[n, round(x / w, 4), round(y / 1024, 4)] for n, x, y in layer])
    points = {k: sc(*v) for k, v in m["points"].items()}
    for k, v in nw["points"].items(): points[k] = [round(v[0] / w, 4), round(v[1] / 1024, 4)]
    roads = [[ren(a), [sc(*p) for p in mids], ren(b)] for a, mids, b in m["roads"]]
    roads += [[a, [[round(x / w, 4), round(y / 1024, 4)] for x, y in mids], b] for a, mids, b in nw["roads"]]
    out[r] = {"spots": spots, "bridge": m["bridge"] + nw["bridge"], "roads": roads, "points": points, "lair": lair, "width": w}
(ROOT / "tools/map_roads.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
